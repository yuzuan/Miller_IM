#!/usr/bin/env python3
"""Review the October overlap tables and record the independent source observations.

Inputs are the full overlap_source_evidence.csv and overlap_28_pair_reaudit.csv generated by 05f.
Outputs in step5_closeout_v2 are overlap_reaudit_checks.csv, overlap_focus_independent.csv
and overlap_supplement_attempts.csv. Each output is created once.
Run python3 NOA_R1/scripts/05g_check_overlap_reassessment.py after 05f in the same scratch copy.
"""

import csv
from collections import Counter
from itertools import combinations
from pathlib import Path


# Read the full provenance tables. The released extracts omit fields used by these checks.
output_dir = Path(__file__).resolve().parents[1] / "step5_closeout_v2"
with (output_dir / "overlap_source_evidence.csv").open(encoding="utf-8", newline="") as handle:
    sources_table = list(csv.DictReader(handle))

with (output_dir / "overlap_28_pair_reaudit.csv").open(encoding="utf-8", newline="") as handle:
    pairs_table = list(csv.DictReader(handle))

if pairs_table and "observed_evidence" not in pairs_table[0]:
    raise ValueError("Generate the full provenance tables with 05f_overlap_reassessment.py in a scratch revision.")

# Compare the observed pair order and coverage against all source combinations.
source_ids = [row["dataset"] for row in sources_table]
pairs_by_source = {(row["source_a"], row["source_b"]): row for row in pairs_table}
allowed_classifications = (
    "known overlap", "evidence supports no overlap", "possible overlap due to shared sources", "insufficient evidence",
)
counts = Counter(row["classification"] for row in pairs_table)
jackson_pair = pairs_by_source[("GSE278456", "GSE276841")]
checks = [
    ("eight_table1_sources", len(sources_table) == 8, len(sources_table)),
    ("28_unique_unordered_pairs", len(pairs_by_source) == len(pairs_table) == 28, len(pairs_by_source)),
    ("all_combinations_once", set(pairs_by_source) == set(combinations(source_ids, 2)), len(set(pairs_by_source))),
    ("four_fixed_classes_only", set(counts) <= set(allowed_classifications), str(dict(counts))),
    ("every_pair_specific_evidence", all(row["observed_evidence"] and row["pair_locator"] for row in pairs_table), ""),
    (
        "every_pair_two_primary_urls",
        all(row["evidence_url_a"].startswith("https://") and row["evidence_url_b"].startswith("https://")
            for row in pairs_table),
        "",
    ),
    (
        "every_pair_two_method_locators",
        all(row["evidence_locator_a"] and row["evidence_locator_b"] for row in pairs_table),
        "",
    ),
    (
        "jackson_shared_ids_known",
        jackson_pair["classification"] == "known overlap" and
        all(patient_id in jackson_pair["observed_evidence"] for patient_id in ("GBM030", "GBM049")),
        "",
    ),
    (
        "CARE_Wang_core_separate",
        pairs_by_source[("GSE174554", "GSE274546")]["classification"] == "evidence supports no overlap",
        "",
    ),
    (
        "trial_Lee_related",
        pairs_by_source[("GSE121810", "GSE154795")]["classification"] == "possible overlap due to shared sources",
        "",
    ),
    (
        "CARE_PDC_related",
        pairs_by_source[("GSE274546", "PDC000514")]["classification"] == "possible overlap due to shared sources",
        "",
    ),
    (
        "trial_UCSF_related",
        pairs_by_source[("GSE174554", "GSE121810")]["classification"] == "possible overlap due to shared sources",
        "",
    ),
    (
        "trial_CARE_MDACC_related",
        pairs_by_source[("GSE274546", "GSE121810")]["classification"] == "possible overlap due to shared sources",
        "",
    ),
    (
        "all_four_class_counts_reported",
        sum(counts.values()) == 28,
        str({label: counts[label] for label in allowed_classifications}),
    ),
]
checks_table = [dict(check=name, passed=passed, detail=detail) for name, passed, detail in checks]

# The observations and retrieval attempts below were recorded in the independent October review.
focus_table = [
    dict(
        pair="GSE174554 × GSE274546",
        evidence_url="https://www.nature.com/articles/s41588-025-02168-4.pdf",
        locator="PDF p2 Results: 59 CARE patients; p2 Results: independent longitudinal cohort ref14; "
        "References ref14 Wang 2022",
        observation="The 59 CARE patients were collected separately from the Wang 2022 external cohort.",
        check="CARE_core_vs_reanalysed_Wang",
        passed=True,
    ),
    dict(
        pair="GSE174554 × GSE274546",
        evidence_url="https://www.nature.com/articles/s43018-022-00475-x",
        locator="Methods > Tumor tissue acquisition",
        observation="Wang used samples from the UCSF Neurosurgery Tissue Bank.",
        check="Wang_source_UCSF",
        passed=True,
    ),
    dict(
        pair="GSE174554 × GSE274546",
        evidence_url="https://www.nature.com/articles/s41588-025-02168-4",
        locator="Methods > Human participants and ethical approval",
        observation="UCSF is absent from the seven CARE sites.",
        check="CARE_seven_sites_no_UCSF",
        passed=True,
    ),
    dict(
        pair="GSE121810 × GSE154795",
        evidence_url="https://escholarship.org/content/qt7gf847t7/"
        "qt7gf847t7_noSplash_e1f45a73ebcbea28921e3801ba049f36.pdf",
        locator="PDF p3 Results Trial patient characteristics; Fig2 caption Pt A/B",
        observation="The trial randomized 35 patients at seven sites between October 2016 and September 2017. "
        "The RNA cases use Pt A/B identifiers.",
        check="original_trial_dates_and_ids",
        passed=True,
    ),
    dict(
        pair="GSE121810 × GSE154795",
        evidence_url="https://www.nature.com/articles/s41467-021-26940-2",
        locator="Methods > Patient tissue collection and single-cell isolation",
        observation="All Lee patients had surgery at UCLA. Neoadjuvant PD-1 therapy was off-label and off-trial.",
        check="Lee_off_trial_and_UCLA",
        passed=True,
    ),
    dict(
        pair="GSE121810 × GSE154795",
        evidence_url="https://www.nature.com/articles/s41467-021-24293-4.pdf",
        locator="PDF p2 Results Characteristics: 13 follow-on off-label versus original NCT02852655",
        observation="The concurrent publication described 13 follow-on patients separately from the original trial. "
        "It supplied no patient-level Pt-to-LB mapping.",
        check="follow_on_not_direct_crosswalk",
        passed=True,
    ),
    dict(
        pair="GSE121810 × GSE154795",
        evidence_url="https://ucla.clinicaltrials.researcherprofiles.org/trial/NCT02852655",
        locator="Locations; Start Date",
        observation="NCT02852655 lists UCLA and UCSF and a September 2016 start. UCLA is shared by the two studies.",
        check="shared_UCLA_trial_site",
        passed=True,
    ),
]
supplement_table = [
    dict(
        url="https://media.springernature.com/original/springer-static/esm/art%3A10.1038%2Fs41588-025-02168-4/"
        "MediaObjects/41588_2025_2168_MOESM2_ESM.xlsx",
        target="CARE Supplementary Table 1",
        attempt="publisher page link 378 clicked 2026-10-20",
        outcome="web tool 400 unsupported application/octet-stream; shell curl failed to connect to local proxy",
        implication="Individual sampling years were unavailable. The table was excluded from timing comparisons.",
    ),
    dict(
        url="https://media.springernature.com/original/springer-static/esm/art%3A10.1038%2Fs41467-021-26940-2/"
        "MediaObjects/41467_2021_26940_MOESM4_ESM.xlsx",
        target="Lee Supplementary Data 1",
        attempt="publisher page link 184 clicked 2026-10-20",
        outcome="web tool cache miss",
        implication="No Pt-to-LB crosswalk was retrieved. The review used the accessible paper and GEO metadata.",
    ),
    dict(
        url="https://pmc.ncbi.nlm.nih.gov/articles/PMC10939876/",
        target="Kim Table S1",
        attempt="PMC article direct open / ScienceDirect publisher open / PDC portal",
        outcome="PMC reCAPTCHA; ScienceDirect 403; PDC JavaScript shell",
        implication="Sampling years for the shared PDC and CARE sites could not be verified.",
    ),
]

# Keep the original report order and block an overwrite with exclusive file creation.
for filename, report_table in (
    ("overlap_reaudit_checks.csv", checks_table),
    ("overlap_focus_independent.csv", focus_table),
    ("overlap_supplement_attempts.csv", supplement_table),
):
    output_path = output_dir / filename
    with output_path.open("x", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(report_table[0]))
        writer.writeheader()
        writer.writerows(report_table)
    if output_path.stat().st_size == 0:
        raise OSError(f"Empty provenance report {filename}")

passed = sum(row["passed"] for row in checks_table) + sum(row["passed"] for row in focus_table)
failed = len(checks_table) + len(focus_table) - passed
print("Overlap checks:", passed, "passed", failed, "failed", "classifications", dict(counts))
if failed:
    raise SystemExit(1)
